import { readFileSync } from "node:fs";
import path from "node:path";
import type { Client } from "@libsql/client";

/**
 * The demo database as one text file.
 *
 * Turso can only be created from a `.db` file or a SQL dump, and a committed
 * `.db` is a bad artefact: binary, invisible in review, and stale the moment a
 * column is added. A SQL dump is the same data in a form git can diff, so this
 * module turns a seeded database into `seed/demo.sql` and applies it to any
 * target - a local file or a `libsql://` URL - in one command.
 *
 * The dump rebuilds rather than merges: every table is dropped and recreated
 * from `schema.sql`, then the rows go in. That keeps one file honest - the
 * columns in the INSERTs always match the CREATE TABLEs beside them - and makes
 * a public demo resettable by running the same file again.
 */

/**
 * Insert order. Parents before children, because a dump replayed into a
 * database with foreign keys enforced must never reference a row that has not
 * arrived yet; the deletes run in the opposite order for the same reason.
 */
export const DEMO_TABLES = [
  "users",
  "players",
  "courses",
  "course_holes",
  "events",
  "societies",
  "society_members",
  "society_events",
  "seasons",
  "season_events",
  "event_state",
  "event_holes",
  "event_admins",
  "groups",
  "event_players",
  "scores",
  "score_audit",
  "scramble_scores",
  "scramble_audit",
  "event_settings",
  "event_pairs",
  "side_game_entries",
  "event_payments",
  "payment_refunds",
] as const;

/** A SQLite string literal: double the quotes, and keep newlines as they are. */
function literal(value: unknown): string {
  if (value === null || value === undefined) return "NULL";
  if (typeof value === "number") return Number.isFinite(value) ? String(value) : "NULL";
  if (typeof value === "bigint") return value.toString();
  if (typeof value === "boolean") return value ? "1" : "0";
  if (value instanceof Uint8Array) return `X'${Buffer.from(value).toString("hex")}'`;
  // Dates and anything else the driver hands back as an object are stored as
  // ISO text in this schema, so toString() is the faithful representation.
  return `'${String(value).replace(/'/g, "''")}'`;
}

/** The DDL, without the comment lines the splitter in db/push.ts also drops. */
export function readDdl(cwd = process.cwd()): string {
  return readFileSync(path.join(cwd, "src/db/schema.sql"), "utf8")
    .split("\n")
    .filter((line) => !line.trim().startsWith("--"))
    .join("\n")
    .trim();
}

export type DemoDump = { sql: string; counts: Record<string, number> };

/**
 * Reads every demo table out of `client` and renders one self-contained script:
 * schema, then a clean slate, then the rows.
 */
export async function buildDemoDump(client: Client, options: { cwd?: string; ddl?: string } = {}): Promise<DemoDump> {
  // schema.sql turns foreign keys on at the top; the dump turns them off while
  // it drops and rebuilds, so that pragma has to go.
  const ddl = (options.ddl ?? readDdl(options.cwd)).replace(/^PRAGMA foreign_keys[^;]*;/m, "").trim();
  const parts: string[] = [
    "-- GolfDay demo database.",
    "--",
    "-- Generated by `npm run seed:dump` from a freshly seeded local database.",
    "-- Apply it to any SQLite/libSQL database, e.g. a free Turso one:",
    "--",
    "--   turso db shell golfday-demo < seed/demo.sql",
    "--",
    "-- It drops and rebuilds every table, then loads the demo day, so it is safe",
    "-- to run again to put a public demo back to normal - and it will NOT keep",
    "-- anything else that was in that database.",
    "-- All the accounts below share the password: golfday123",
    "",
    "PRAGMA foreign_keys = OFF;",
    "",
    "-- Fresh tables, children before parents.",
    ...[...DEMO_TABLES].reverse().map((table) => `DROP TABLE IF EXISTS ${table};`),
    "",
    ddl,
    "",
  ];

  const counts: Record<string, number> = {};
  for (const table of DEMO_TABLES) {
    const result = await client.execute(`SELECT * FROM ${table}`);
    counts[table] = result.rows.length;
    if (!result.rows.length) continue;
    const columns = result.columns;
    const statements = result.rows.map(
      (row) => `INSERT INTO ${table} (${columns.join(", ")}) VALUES (${columns.map((c) => literal(row[c])).join(", ")});`,
    );
    parts.push("", `-- ${table} (${result.rows.length})`, ...statements);
  }

  parts.push("", "PRAGMA foreign_keys = ON;", "");
  return { sql: parts.join("\n"), counts };
}

/**
 * Replays a dump. `executeMultiple` is used when the client has it (it handles
 * multi-statement strings properly, so a semicolon inside a description cannot
 * split a statement in half); otherwise the script is split on statement
 * boundaries the same way `db/push.ts` does it.
 */
export async function applySql(client: Client, sql: string): Promise<void> {
  const multi = (client as unknown as { executeMultiple?: (sql: string) => Promise<void> }).executeMultiple;
  if (typeof multi === "function") {
    await multi.call(client, sql);
    return;
  }
  const statements = sql
    .split("\n")
    .filter((line) => !line.trim().startsWith("--"))
    .join("\n")
    .split(";")
    .map((s) => s.trim())
    .filter(Boolean);
  for (const statement of statements) await client.execute(statement);
}
